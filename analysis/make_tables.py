"""Rebuild Tables 8-25 of the paper (and the statistical tests reported with Figures 6-17) from the result files.

Usage (from the repository root, after running the experiments):
    python analysis/make_tables.py            # writes results/tables.md and prints it
"""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import numpy as np
from src.config import RESULTS
from src.results import (load_all, load_json, mean_std, friedman_nemenyi, ranking_candidates, CLASSICAL, STATIC,
                         FAMILY_NAMES)

OUT = []
emit = OUT.append
pm4 = lambda v: '%.4f ± %.4f' % mean_std(v)
pm3 = lambda v: '%.3f ± %.3f' % mean_std(v)


def md_table(header, rows):
    emit('| ' + ' | '.join(header) + ' |')
    emit('|' + '|'.join(['---'] * len(header)) + '|')
    for r in rows:
        emit('| ' + ' | '.join(str(x) for x in r) + ' |')
    emit('')


def metrics_table(fam_results, names, title):
    emit(f'### {title}\n')
    best_acc = max(np.mean(fam_results[n]['acc']) for n in names)
    best_auc = max(np.mean(fam_results[n]['auc']) for n in names)
    rows = []
    for n in names:
        r = fam_results[n]
        cell = lambda m, best: ('**%s**' if np.isclose(np.mean(r[m]), best) else '%s') % pm4(r[m])
        rows.append([n, cell('acc', best_acc), pm4(r['prec']), pm4(r['rec']), pm4(r['f1']), cell('auc', best_auc)])
    md_table(['Model', 'Accuracy', 'Precision', 'Recall', 'F1-score', 'AUC-ROC'], rows)


def friedman_line(scores, metric):
    t = friedman_nemenyi(scores)
    ranks = ', '.join(f'{n} {r:.2f}' for n, r in sorted(t['ranks'].items(), key=lambda x: x[1]))
    p = 'p < 0.001' if t['p'] < 0.001 else f"p = {t['p']:.4f}"
    emit(f"Friedman test on {metric}: chi2 = {t['stat']:.3f}, {p}; Nemenyi CD = {t['cd']:.3f}; average ranks: {ranks}.\n")


def ranking_table(F, title, fig):
    emit(f'### {title}\n')
    rows, prev, rank = [], None, 0
    for i, (n, r) in enumerate(ranking_candidates(F), 1):
        auc = np.mean(r['auc'])
        if prev is None or not np.isclose(auc, prev):
            rank = i
        prev = auc
        rows.append([rank, n, pm4(r['acc']), pm4(r['prec']), pm4(r['rec']), pm4(r['f1']), pm4(r['auc'])])
    md_table(['Rank', 'Model (category)', 'Accuracy', 'Precision', 'Recall', 'F1-score', 'AUC-ROC'], rows)
    top5 = ranking_candidates(F)[:5]
    friedman_line({n: r['auc'] for n, r in top5}, f'AUC-ROC, five best models (Figure {fig}a)')


def best_of(fam_results):
    """Best model by mean AUC; models with the same accuracy and an AUC within 0.0005 are reported together
    (e.g. DESP / FIRE-DESP)."""
    best = max(fam_results, key=lambda n: np.mean(fam_results[n]['auc']))
    ties = [n for n in fam_results if np.mean(fam_results[n]['acc']) == np.mean(fam_results[best]['acc'])
            and abs(np.mean(fam_results[n]['auc']) - np.mean(fam_results[best]['auc'])) < 5e-4]
    ties.sort(key=lambda n: (n.startswith('FIRE'), n))
    return ' / '.join(ties), fam_results[best]


def main():
    A = load_all()
    emit('# Tables of the paper, rebuilt from the result files\n')
    emit('Mean ± standard deviation over the 10 random 70/30 splits (random states 0-9); best values in bold. '
         'Generated by `analysis/make_tables.py`.\n')
    num = 8
    for fusion, label, figs in [('early', 'Early Fusion', [6, 7, 8, 9, 10]), ('late', 'Late Fusion', [12, 13, 14, 15, 16])]:
        F = A[fusion]
        emit(f'## {label}\n')
        for fam, fig in zip(['classical', 'static', 'pool1', 'pool2', 'pool3'], figs):
            names = CLASSICAL if fam == 'classical' else STATIC if fam == 'static' else list(F[fam])
            metrics_table(F[fam], names, f'Table {num}. {FAMILY_NAMES[fam]} - {label}')
            friedman_line({n: F[fam][n]['acc'] for n in names}, f'accuracy (Figure {fig}b)')
            num += 1
        best_pool = max(['pool1', 'pool2', 'pool3'], key=lambda p: max(np.mean(F[p][n]['auc']) for n in F[p]))
        emit(f'Best DES pool by AUC: {best_pool}.\n')
        ranking_table(F, f'Table {num}. DES methods (Pool 2) and static ensembles ranked by AUC-ROC - {label}', figs[-1] + 1)
        num += 1

    # ---------------------------------------------------------------- additional analyses (Early Fusion)
    X = load_json('additional_analyses.json')
    M = load_json('early_fusion.json')
    emit('## Additional analyses (Early Fusion)\n')
    emit('### Table 20. Modality ablation (accuracy / AUC-ROC)\n')
    labels = {'tabular': 'Tabular', 'text': 'Text', 'timeseries': 'CGM', 'tabular+text': 'Tabular + Text',
              'tabular+timeseries': 'Tabular + CGM', 'text+timeseries': 'Text + CGM',
              'tabular+text+timeseries': 'All (NN-selected features)',
              'raw:tabular+text+timeseries': 'All (without NN selection)'}
    rows = [[lab] + [pm3([r['abl'][k][m][x] for r in X]) for m in ['LR', 'CB', 'DESP'] for x in ['acc', 'auc']]
            for k, lab in labels.items()]
    md_table(['Modalities', 'LR acc.', 'LR AUC', 'CB acc.', 'CB AUC', 'DESP (Pool 2) acc.', 'DESP (Pool 2) AUC'], rows)

    emit('### Table 21. Class-imbalance strategies (AUC-ROC and sensitivity for SH cases, mean)\n')
    rows = [[lab] + ['%.3f' % np.mean([r['imb'][s][m][x] for r in X]) for m in ['LR', 'CB', 'DESP'] for x in ['auc', 'sens_case']]
            for s, lab in [('smote', 'SMOTE'), ('weights', 'Class weights'), ('rus', 'Random undersampling'), ('none', 'None')]]
    md_table(['Strategy', 'LR AUC', 'LR sens.', 'CB AUC', 'CB sens.', 'DESP AUC', 'DESP sens.'], rows)

    emit('### Table 22. Sensitivity of DES (Pool 3) to k (mean AUC-ROC)\n')
    rows = [[k] + ['%.3f' % np.mean([r['kabl'][d][k]['auc'] for r in M]) for d in ['DESP', 'KNORAE', 'FIRE-DESKNN']]
            + ['%.3f' % np.mean([r['des_ho'][d][k]['auc'] for r in M]) for d in ['DESP', 'KNORAE', 'FIRE-DESKNN']]
            for k in ['3', '5', '7', '9', '11', '13', '15']]
    md_table(['k', 'DESP (main)', 'KNORAE (main)', 'FIRE-DESKNN (main)', 'DESP (held-out DSEL)', 'KNORAE (held-out DSEL)',
              'FIRE-DESKNN (held-out DSEL)'], rows)
    members = {n[7:]: np.mean([r['des_ho'][n]['auc'] for r in M]) for n in M[0]['des_ho'] if n.startswith('member_')}
    emit('Pool members trained on the held-out-DSEL training subset (mean AUC): '
         + ', '.join(f'{n} {v:.3f}' for n, v in sorted(members.items(), key=lambda x: -x[1])) + '.\n')

    emit('### DES selection analysis (DESP, Pool 3, k = 7)\n')
    rows = []
    for proto, lab in [('main', 'Main protocol'), ('heldout', 'Held-out DSEL')]:
        s = lambda key: np.mean([r['sel'][proto][key] for r in X])
        rows.append([lab, '%.2f' % s('mean_selected'), '%.1f%%' % (100 * s('frac_all_selected')), '%.3f' % s('mean_competence')])
    md_table(['Protocol', 'Classifiers selected (mean)', 'Patients with all classifiers selected', 'Mean local competence'], rows)

    emit('### Table 23. Modality-level Shapley values (mean absolute contribution, share of total)\n')
    rows = []
    for m, lab in [('LR', 'LR (static)'), ('CB', 'CB (static)'), ('DESP', 'DESP (dynamic)'), ('DESP-heldout', 'DESP, held-out DSEL')]:
        d = {mod: np.mean([r['shap'][m][mod] for r in X]) for mod in ['tabular', 'text', 'timeseries']}
        tot = sum(d.values())
        rows.append([lab] + ['%.3f (%.0f%%)' % (d[mod], 100 * d[mod] / tot) for mod in ['tabular', 'text', 'timeseries']])
    md_table(['Model', 'Tabular', 'Text', 'CGM'], rows)

    emit('### Table 24. Computational cost (mean over the 10 runs; machine-dependent)\n')
    sel = [('LR', 'classical', 'LR'), ('SVC', 'classical', 'SVC'), ('RF', 'static', 'RF'), ('XGB', 'static', 'XGB'),
           ('CB', 'static', 'CB'), ('DESP (Pool 1)', '1', 'DESP'), ('DESP (Pool 2)', '2', 'DESP'), ('DESP (Pool 3)', '3', 'DESP'),
           ('KNORAE (Pool 3)', '3', 'KNORAE'), ('FIRE-DESKNN (Pool 3)', '3', 'FIRE-DESKNN')]
    get = lambda r, fam, n: r[fam][n] if fam in ('classical', 'static') else r['des'][fam][n]
    rows = [[lab] + ['%.3f' % np.mean([get(r, fam, n)['t_fit_s'] for r in M]), '%.3f' % np.mean([get(r, fam, n)['t_inf_ms'] for r in M]),
                     '%.0f' % np.mean([get(r, fam, n)['size_kb'] for r in M])] for lab, fam, n in sel]
    md_table(['Model', 'Training (s)', 'Inference (ms/patient)', 'Size (KB)'], rows)

    emit('### Table 25. Best model of each category (selected by AUC-ROC)\n')
    rows = []
    for fusion, lab in [('early', 'Early'), ('late', 'Late')]:
        for fam in ['classical', 'static', 'pool2']:
            n, r = best_of(A[fusion][fam])
            rows.append([lab, FAMILY_NAMES[fam], n, pm4(r['acc']), pm4(r['auc'])])
    md_table(['Fusion', 'Category', 'Best model', 'Accuracy', 'AUC-ROC'], rows)

    text = '\n'.join(OUT)
    (RESULTS / 'tables.md').write_text(text)
    print(text)


if __name__ == '__main__':
    main()
